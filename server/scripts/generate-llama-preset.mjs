/**
 * Generates the llama-server router preset (models.ini) from the model
 * registry, so the ids the API resolves and the ids the router serves are
 * guaranteed to be the same strings.
 *
 *   node scripts/generate-llama-preset.mjs --models-dir ../models --out ../deploy/llama/models.ini
 *
 * Models whose GGUF is not on disk are skipped with a warning rather than
 * written out: the router refuses to start when a preset points at a missing
 * file, and a partially-downloaded host should still serve what it has. The
 * skipped ones surface in the UI as unavailable, because the provider marks
 * anything absent from /v1/models as `weights-missing`.
 */
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, isAbsolute, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import dotenv from 'dotenv';

const here = dirname(fileURLToPath(import.meta.url));

// The registry pulls in config/env.js, whose dotenv.config() resolves against
// the current directory. This script runs from deploy/ and from the repo root,
// so point dotenv at server/.env explicitly rather than relying on cwd.
dotenv.config({ path: resolve(here, '..', '.env') });

const { MODEL_REGISTRY } = await import('../src/services/ai/modelRegistry.js');

function arg(name, fallback) {
  const i = process.argv.indexOf(`--${name}`);
  return i !== -1 && process.argv[i + 1] ? process.argv[i + 1] : fallback;
}

const modelsDir = resolve(here, arg('models-dir', join(here, '..', '..', 'models')));
const outPath = resolve(here, arg('out', join(here, '..', '..', 'deploy', 'llama', 'models.ini')));
// llama-server divides --ctx-size across --parallel slots, so each child needs
// the registry's per-request window multiplied by the slot count or concurrent
// generations would silently get half the advertised context.
const parallel = Number(arg('parallel', '2'));

const chatModels = MODEL_REGISTRY.filter((m) => m.role === 'chat');

const present = [];
const missing = [];
for (const model of chatModels) {
  const path = isAbsolute(model.file) ? model.file : join(modelsDir, model.file);
  (existsSync(path) ? present : missing).push({ ...model, path });
}

if (!present.length) {
  console.error(`[x] No chat model GGUFs found in ${modelsDir}`);
  console.error('    Download them with deploy/scripts/fetch-models.sh (or fetch-models.ps1).');
  process.exit(1);
}

// Kept to ASCII: this file is parsed by llama.cpp's C++ INI reader, and there
// is no reason to make its encoding a variable.
const lines = [
  '; llama-server router presets for ATOZAS AI.',
  '; GENERATED by server/scripts/generate-llama-preset.mjs - do not edit by hand.',
  '; Section names are the model ids the API sends in the OpenAI `model` field.',
  '',
  'version = 1',
  '',
];

for (const model of present) {
  lines.push(`; ${model.name}`);
  lines.push(`; ${model.license}${model.commercialUse ? ' - commercial use permitted' : ''}`);
  lines.push(`[${model.id}]`);
  // Forward slashes work on both platforms and avoid INI escaping questions.
  lines.push(`m = ${model.path.replace(/\\/g, '/')}`);
  lines.push(`ctx-size = ${(model.runtime?.contextWindow ?? 8192) * parallel}`);
  lines.push(`parallel = ${parallel}`);
  lines.push('');
}

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, lines.join('\n'), 'utf8');

console.log(`Wrote ${outPath}`);
for (const m of present) console.log(`  + ${m.id}`);
for (const m of missing) console.log(`  - ${m.id} (missing ${m.file})`);
